#!/usr/bin/env node
// Deterministic pure source emitter; executes only under Node on the host.
// Usage: node games/apocalyptic-lists/tools/generate-room-data.mjs
// Optional --check verifies committed generated output without modifying it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const game = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(fs.readFileSync(path.join(game, 'implementation/encounters.json'), 'utf8'));
if (src.schema !== 'AL-COMBAT-PORT-1' || src.variants.length !== 81) throw Error('invalid encounter source');
const quote = v => JSON.stringify(v);
const arr = v => `[${v.map(quote).join(', ')}]`;
// Allocate a fresh object for every use of every actor preset. A shared runtime
// instance would incorrectly couple rooms, marks, and subsequent trials.
// The canonical JSON is the authority; numeric preset keys are private generated
// implementation details, never game-facing identifiers.
const actorPresets = [];
const actorPresetIDs = new Map();
for (const v of src.variants) for (const a of v.actors) {
 const serialized = JSON.stringify(a);
 if (!actorPresetIDs.has(serialized)) {
  actorPresetIDs.set(serialized, actorPresets.length + 1);
  actorPresets.push(a);
 }
}
const lines = ['// AUTO-GENERATED by tools/generate-room-data.mjs from implementation/encounters.json',
'// DO NOT HAND EDIT. Native MakeCode Arcade TypeScript, no runtime parsing/imports.',
'// Actor preset keys are private; every call constructs a fresh mutable ActorSpec.',
'namespace apocRooms {',
'    function mark(side: apocTypes.Side, index: number, all: boolean, bonus: apocTypes.PowerSource): apocTypes.PowerSource {',
'        const v = new apocTypes.PowerSource(); v.side = side; v.index = index; v.isAll = all; v.bonus = bonus; return v;',
'    }',
'    function actor(id: string, side: apocTypes.Side, hp: number, maxHP: number, ability: string, trait: string): apocTypes.ActorSpec {',
'        const a = new apocTypes.ActorSpec();',
'        a.id = id; a.artKey = id; a.side = side; a.hp = hp; a.maxHP = maxHP;',
'        a.ability = ability; a.trait = trait; return a;',
'    }',
'    function actorPreset(key: number): apocTypes.ActorSpec {',
'        switch (key) {'];
const stat = s => s === 'ally' ? 'apocTypes.Side.Ally' : 'apocTypes.Side.Enemy';
function markExpr(p) { return p ? `mark(${stat(p.side)}, ${p.index}, ${!!p.isAll}, ${markExpr(p.bonus)})` : 'null'; }
for (let i = 0; i < actorPresets.length; i++) {
 const a = actorPresets[i], key = i + 1;
 const expr = `actor(${quote(a.id)}, ${stat(a.side)}, ${a.hp}, ${a.maxHP}, ${quote(a.ability)}, ${quote(a.trait)})`;
 if (a.present !== true || a.held !== false || a.ward || a.venom || a.empower) {
  lines.push(`            case ${key}: { const a = ${expr}; // ${a.id}`);
  if (a.present !== true) lines.push(`                a.present = ${!!a.present};`);
  if (a.held !== false) lines.push(`                a.held = ${!!a.held};`);
  for (const effect of ['ward','venom','empower']) if (a[effect]) lines.push(`                a.${effect} = ${markExpr(a[effect])};`);
  lines.push('                return a; }');
 } else lines.push(`            case ${key}: return ${expr}; // ${a.id}`);
}
lines.push('        }', '        return null;', '    }');
// Nine small generated switches: each owns three rooms × three variants.
// A giant 81-case PXT function is a compiler-pressure risk even if ES5 tsc accepts it.
for (let group = 0; group < 9; group++) {
 lines.push(`    function roomGroup${group}(s: apocTypes.RoomSpec, key: number): apocTypes.RoomSpec {`,
            '        const b = s.battle;', '        switch (key) {');
 for (const v of src.variants.filter(v => Math.floor((v.room - 1) / 3) === group)) {
 const n = (v.room - 1) * 3 + v.variant;
 lines.push(`            case ${n}: { // R${String(v.room).padStart(2,'0')}-V${v.variant}`);
 lines.push(`                s.instruction = ${quote(v.instruction)};`);
 for (const name of ['allyMoves','allyValues','enemyMoves','enemyValues']) lines.push(`                b.${name} = ${arr(v.lists[name])};`);
 lines.push(`                b.allyTargetIDs = ${arr(v.lists.allyTargets)};`, `                b.enemyTargetIDs = ${arr(v.lists.enemyTargets)};`);
 lines.push(`                b.goal = ${quote(v.goal)}; b.requiredIDs = ${arr(v.requiredIDs)};`);
 // The actor factory always returns a NEW ActorSpec and new PowerSource marks.
 // Preserve authored iteration/display order exactly, including duplicate roles.
 for (const a of v.actors) lines.push(`                b.actors.push(actorPreset(${actorPresetIDs.get(JSON.stringify(a))})); // ${a.id}`);
 lines.push(`                s.rosterIDs = ${arr(v.rosterIDs)};`);
 const source = [16,21,26].includes(v.room) ? v.lists.enemyMoves : v.sourceMoves;
 lines.push(`                s.sourceMoves = ${arr(source)};`);
 const editable = [...new Set(v.stations.flatMap(s=>s.editableLists))];
 lines.push(`                s.editableLists = ${arr(editable)};`);
 lines.push(`                s.allowHold = ${v.stations.some(s=>s.allowHold)}; s.allowBanish = ${v.stations.some(s=>s.allowBanish)};`);
 lines.push(`                s.twoStations = ${v.stations.length===2};`);
 lines.push(`                s.primaryIndex = ${v.stations[0].markedIndex}; s.secondaryIndex = ${v.stations[1]?.markedIndex ?? -1}; s.numberHint = ${v.numberHint};`);
 lines.push('                return s;', '            }');
}
 lines.push('        }', '        return null;', '    }');
}
lines.push('    export function spec(room: apocTypes.Room, variant: number): apocTypes.RoomSpec {',
'        if (room < 1 || room > 27 || variant < 1 || variant > 3 ||',
'            room !== Math.floor(room) || variant !== Math.floor(variant)) return null;',
'        const s = new apocTypes.RoomSpec();',
'        s.battle = new apocTypes.BattleSpec(); s.battle.actors = [];',
'        s.room = room; s.variant = variant;',
'        const key = (room - 1) * 3 + variant;');
for (let group = 0; group < 9; group++)
 lines.push(`        if (room <= ${(group + 1) * 3}) return roomGroup${group}(s, key);`);
lines.push('        return null;', '    }', '}', '');
const goalsPath=path.join(game,'implementation/supplied-world/goals.ts');
const prefix=fs.readFileSync(path.join(game, 'tools/goals-runtime-template.txt'),'utf8');
const goalLines=['    // BEGIN DETERMINISTIC GENERATED GOALS'];
// Split the 81 canonical objective literals into nine bounded functions.
// Runtime only constructs the selected objective; no JSON parser, imports,
// shared mutable expected-state objects or task-answer helpers are added.
function expectBattle(b, indent='                ') {
 const out=[];
 for (const n of ['allyMoves','allyValues','enemyMoves','enemyValues']) out.push(`${indent}b.${n} = ${arr(b[n])};`);
 out.push(`${indent}b.allyTargetIDs = ${arr(b.allyTargets)};`);
 out.push(`${indent}b.enemyTargetIDs = ${arr(b.enemyTargets)};`);
 return out;
}
for (let group = 0; group < 9; group++) {
 goalLines.push(`    function expectedGroup${group}(e: Expect, key: number): Expect {`,
                '        const b = e.lists;', '        switch (key) {');
for (const v of src.variants.filter(v => Math.floor((v.room - 1) / 3) === group)) {
 goalLines.push(`            case ${(v.room-1)*3+v.variant}: {`);
 goalLines.push(...expectBattle(v.expected.lists));
 goalLines.push(`                e.rosterIDs = ${arr(v.expected.rosterIDs)}; e.sourceMoves = ${arr(v.expected.sourceMoves)};`);
 for (const ef of v.expected.allowedEffectStates) {
  goalLines.push(`                e.heldChoices.push(${arr(ef.heldActorIds)}); e.banishedChoices.push(${arr(ef.banishedActorIds)});`);
 }
 for (const h of v.expected.history) {
  for (const [name,key] of [['histBefore','beforeLists'],['histAfter','afterLists']]) {
   goalLines.push('                { const b = new apocTypes.BattleSpec();');
   goalLines.push(...expectBattle(h[key], '                  '));
   goalLines.push(`                  e.${name}.push(b); }`);
  }
 }
 goalLines.push('                return e;', '            }');
}
goalLines.push('        }', '        return null;', '    }');
}
goalLines.push('    function expected(room: apocTypes.Room, variant: number): Expect {',
 '        if (room < 1 || room > 27 || variant < 1 || variant > 3 ||',
 '            room !== Math.floor(room) || variant !== Math.floor(variant)) return null;',
 '        const e = new Expect(); e.lists = new apocTypes.BattleSpec();',
 '        const key = (room - 1) * 3 + variant;');
for (let group = 0; group < 9; group++)
 goalLines.push(`        if (room <= ${(group + 1) * 3}) return expectedGroup${group}(e, key);`);
goalLines.push('        return null;', '    }', '}', '');
const outputs=[[path.join(game,'implementation/supplied-world/rooms.ts'),lines.join('\n')],[goalsPath,prefix+goalLines.join('\n')]];
const check=process.argv.includes('--check');
for (const [target,data] of outputs) {
 if (check) { if (!fs.existsSync(target) || fs.readFileSync(target,'utf8')!==data) throw Error(`generated source differs: ${target}`); }
 else fs.writeFileSync(target,data,'utf8');
}
console.log(`${check?'Verified':'Generated'} 81 room specs + 81 observable goal presets`);
